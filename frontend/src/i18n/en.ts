/**
 * The English form of the app-wide macro triplet: `{P} P · {C} C · {F} F`. Same rules as the
 * German one (middots, integer-rounded, no `g`); only the carbs label differs.
 */
function formatMacroTriplet(protein: number, carbs: number, fat: number): string {
  return `${Math.round(protein)} P · ${Math.round(carbs)} C · ${Math.round(fat)} F`;
}

const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);

